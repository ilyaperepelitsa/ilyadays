-- ilyadays.com fitness: programs, gyms, sessions, sets, progression state, weigh-ins, plan adjustments
-- Date: 2026-11-08 · Project: dedicated ilyadays Supabase project
-- ============================================================================
--
-- Every row belongs to a user (user_id = auth.uid() at insert). Everyone — signed in or not — can READ, so visitors
-- can watch the owner's progress. Only a user who is allowed to train here can WRITE their own rows:
-- public.fitness_can_write() = the site admin (public.is_admin(), from 20261006110000_ilyadays_admin.sql) or a user
-- with a row in public.fitness_profiles (friends, enabled by the owner in SQL Editor).
--
-- Ids are generated by the browser (uuid) so an offline outbox can replay writes as idempotent upserts.
-- Requires: 20261006110000_ilyadays_admin.sql. Safe to re-run: every statement is idempotent.

BEGIN;

-- Writes are gated by public.is_admin() from 20261006110000_ilyadays_admin.sql. In a project where is_admin() belongs
-- to another app (the shared Typekana project), that app's admins would gate fitness writes and the first of them to
-- open /fitness would become the owner: refuse to install there.
DO $$
BEGIN
  IF to_regclass('public.ilyadays_admins') IS NULL THEN
    RAISE EXCEPTION 'Run 20261006110000_ilyadays_admin.sql first, in the dedicated ilyadays Supabase project: fitness writes are gated by its public.is_admin().';
  END IF;
END;
$$;

-- ---------------------------------------------------------------- helpers

CREATE OR REPLACE FUNCTION public.fitness_touch()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = ''
AS $$
BEGIN
  NEW.updated_at := now();
  RETURN NEW;
END;
$$;
REVOKE ALL ON FUNCTION public.fitness_touch() FROM PUBLIC, anon, authenticated;

-- ---------------------------------------------------------------- profiles: who may write, whose data visitors see

CREATE TABLE IF NOT EXISTS public.fitness_profiles (
  user_id       uuid        PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  display_name  text        NOT NULL DEFAULT '' CHECK (char_length(display_name) <= 80),
  is_owner      boolean     NOT NULL DEFAULT false,
  is_public     boolean     NOT NULL DEFAULT true,
  settings      jsonb       NOT NULL DEFAULT '{}'::jsonb,
  created_at    timestamptz NOT NULL DEFAULT now(),
  updated_at    timestamptz NOT NULL DEFAULT now()
);
COMMENT ON TABLE public.fitness_profiles IS
  'Users allowed to log training. is_owner marks the site owner whose plan visitors see by default.';
-- exactly one owner
CREATE UNIQUE INDEX IF NOT EXISTS fitness_profiles_one_owner ON public.fitness_profiles ((true)) WHERE is_owner;

DROP TRIGGER IF EXISTS fitness_profiles_touch ON public.fitness_profiles;
CREATE TRIGGER fitness_profiles_touch BEFORE INSERT OR UPDATE ON public.fitness_profiles
  FOR EACH ROW EXECUTE FUNCTION public.fitness_touch();

CREATE OR REPLACE FUNCTION public.fitness_can_write()
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
  SELECT public.is_admin()
      OR EXISTS (SELECT 1 FROM public.fitness_profiles WHERE user_id = (SELECT auth.uid()));
$$;
REVOKE ALL ON FUNCTION public.fitness_can_write() FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.fitness_can_write() TO authenticated;

-- The owner's user id, for visitors (null until the owner has a profile).
CREATE OR REPLACE FUNCTION public.fitness_owner_id()
RETURNS uuid
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
  SELECT user_id FROM public.fitness_profiles WHERE is_owner LIMIT 1;
$$;
REVOKE ALL ON FUNCTION public.fitness_owner_id() FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.fitness_owner_id() TO anon, authenticated;

ALTER TABLE public.fitness_profiles ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "fitness_profiles readable by everyone" ON public.fitness_profiles;
CREATE POLICY "fitness_profiles readable by everyone" ON public.fitness_profiles
  FOR SELECT TO anon, authenticated USING (true);
-- The admin creates their own profile from the app (becoming the owner if there is none yet).
-- Friends' rows are inserted by the owner in SQL Editor.
DROP POLICY IF EXISTS "fitness_profiles insert by admin for self" ON public.fitness_profiles;
CREATE POLICY "fitness_profiles insert by admin for self" ON public.fitness_profiles
  FOR INSERT TO authenticated
  WITH CHECK (user_id = (SELECT auth.uid()) AND public.is_admin());
DROP POLICY IF EXISTS "fitness_profiles update own" ON public.fitness_profiles;
CREATE POLICY "fitness_profiles update own" ON public.fitness_profiles
  FOR UPDATE TO authenticated
  USING (user_id = (SELECT auth.uid()))
  WITH CHECK (user_id = (SELECT auth.uid()) AND (is_owner = public.is_admin() OR NOT is_owner));
REVOKE ALL ON public.fitness_profiles FROM anon, authenticated;
GRANT SELECT ON public.fitness_profiles TO anon;
GRANT SELECT, INSERT, UPDATE ON public.fitness_profiles TO authenticated;

-- ---------------------------------------------------------------- generic per-user tables

-- programs: a program version. spec = Program (src/lib/fitness/types.ts)
CREATE TABLE IF NOT EXISTS public.fitness_programs (
  id          uuid        PRIMARY KEY,
  user_id     uuid        NOT NULL DEFAULT auth.uid() REFERENCES auth.users(id) ON DELETE CASCADE,
  active      boolean     NOT NULL DEFAULT true,
  spec        jsonb       NOT NULL,
  created_at  timestamptz NOT NULL DEFAULT now(),
  updated_at  timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS fitness_programs_user ON public.fitness_programs (user_id, updated_at DESC);

-- gyms: equipment profiles. spec = Gym
CREATE TABLE IF NOT EXISTS public.fitness_gyms (
  id          uuid        PRIMARY KEY,
  user_id     uuid        NOT NULL DEFAULT auth.uid() REFERENCES auth.users(id) ON DELETE CASCADE,
  spec        jsonb       NOT NULL,
  created_at  timestamptz NOT NULL DEFAULT now(),
  updated_at  timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS fitness_gyms_user ON public.fitness_gyms (user_id);

-- sessions
CREATE TABLE IF NOT EXISTS public.fitness_sessions (
  id             uuid        PRIMARY KEY,
  user_id        uuid        NOT NULL DEFAULT auth.uid() REFERENCES auth.users(id) ON DELETE CASCADE,
  program_id     uuid        NULL,
  gym_id         uuid        NULL,
  day_key        text        NOT NULL CHECK (day_key ~ '^[A-Za-z0-9_-]{1,16}$'),
  started_at     timestamptz NOT NULL,
  ended_at       timestamptz NULL,
  status         text        NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'finished', 'auto_closed', 'abandoned')),
  bodyweight_kg  numeric(5,2) NULL CHECK (bodyweight_kg IS NULL OR (bodyweight_kg > 20 AND bodyweight_kg < 400)),
  readiness      jsonb       NOT NULL DEFAULT '{}'::jsonb,
  notes          text        NOT NULL DEFAULT '' CHECK (char_length(notes) <= 2000),
  created_at     timestamptz NOT NULL DEFAULT now(),
  updated_at     timestamptz NOT NULL DEFAULT now(),
  CHECK (ended_at IS NULL OR ended_at >= started_at),
  -- lets fitness_sets reference (session, owner) so nobody can attach a set to another user's session
  CONSTRAINT fitness_sessions_id_user UNIQUE (id, user_id)
);
CREATE INDEX IF NOT EXISTS fitness_sessions_user_started ON public.fitness_sessions (user_id, started_at DESC);

-- sets: one logged set (warm-ups included)
CREATE TABLE IF NOT EXISTS public.fitness_sets (
  id            uuid        PRIMARY KEY,
  user_id       uuid        NOT NULL DEFAULT auth.uid() REFERENCES auth.users(id) ON DELETE CASCADE,
  session_id    uuid        NOT NULL,
  slot_id       text        NOT NULL CHECK (char_length(slot_id) <= 32),
  exercise_id   text        NOT NULL CHECK (exercise_id ~ '^[a-z0-9-]{1,64}$'),
  set_index     smallint    NOT NULL CHECK (set_index >= 0 AND set_index < 50),
  kind          text        NOT NULL DEFAULT 'working' CHECK (kind IN ('warmup', 'working', 'backoff', 'amrap')),
  planned_kg    numeric(6,2) NOT NULL DEFAULT 0 CHECK (planned_kg >= 0 AND planned_kg < 1000),
  planned_reps  smallint    NOT NULL DEFAULT 0 CHECK (planned_reps >= 0 AND planned_reps < 500),
  kg            numeric(6,2) NOT NULL CHECK (kg >= 0 AND kg < 1000),
  reps          smallint    NOT NULL CHECK (reps >= 0 AND reps < 500),
  rir           numeric(3,1) NULL CHECK (rir IS NULL OR (rir >= 0 AND rir <= 10)),
  done_at       timestamptz NOT NULL,
  created_at    timestamptz NOT NULL DEFAULT now(),
  updated_at    timestamptz NOT NULL DEFAULT now(),
  -- the set's session must belong to the same user (a plain FK on id alone would let a friend attach sets to the
  -- owner's session: foreign-key checks bypass RLS)
  CONSTRAINT fitness_sets_session_owner FOREIGN KEY (session_id, user_id)
    REFERENCES public.fitness_sessions (id, user_id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS fitness_sets_session ON public.fitness_sets (session_id, set_index);
CREATE INDEX IF NOT EXISTS fitness_sets_user_exercise ON public.fitness_sets (user_id, exercise_id, done_at DESC);

-- exercise_state: progression memory per exercise. spec = ExerciseState
CREATE TABLE IF NOT EXISTS public.fitness_exercise_state (
  user_id      uuid        NOT NULL DEFAULT auth.uid() REFERENCES auth.users(id) ON DELETE CASCADE,
  exercise_id  text        NOT NULL CHECK (exercise_id ~ '^[a-z0-9-]{1,64}$'),
  spec         jsonb       NOT NULL,
  created_at   timestamptz NOT NULL DEFAULT now(),
  updated_at   timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (user_id, exercise_id)
);

-- bodyweight: weigh-ins
CREATE TABLE IF NOT EXISTS public.fitness_bodyweight (
  id            uuid        PRIMARY KEY,
  user_id       uuid        NOT NULL DEFAULT auth.uid() REFERENCES auth.users(id) ON DELETE CASCADE,
  measured_at   timestamptz NOT NULL,
  weight_kg     numeric(5,2) NOT NULL CHECK (weight_kg > 20 AND weight_kg < 400),
  body_fat_pct  numeric(4,1) NULL CHECK (body_fat_pct IS NULL OR (body_fat_pct > 1 AND body_fat_pct < 70)),
  note          text        NOT NULL DEFAULT '' CHECK (char_length(note) <= 500),
  created_at    timestamptz NOT NULL DEFAULT now(),
  updated_at    timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS fitness_bodyweight_user_at ON public.fitness_bodyweight (user_id, measured_at DESC);

-- adjustments: AI / engine / manual plan changes with their inputs and outputs
CREATE TABLE IF NOT EXISTS public.fitness_adjustments (
  id          uuid        PRIMARY KEY,
  user_id     uuid        NOT NULL DEFAULT auth.uid() REFERENCES auth.users(id) ON DELETE CASCADE,
  source      text        NOT NULL CHECK (source IN ('ai', 'engine', 'manual')),
  input       jsonb       NOT NULL DEFAULT '{}'::jsonb,
  output      jsonb       NOT NULL DEFAULT '{}'::jsonb,
  applied     boolean     NOT NULL DEFAULT false,
  created_at  timestamptz NOT NULL DEFAULT now(),
  updated_at  timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS fitness_adjustments_user ON public.fitness_adjustments (user_id, created_at DESC);

-- ---------------------------------------------------------------- triggers, RLS, grants for every per-user table

DO $$
DECLARE
  t text;
BEGIN
  FOREACH t IN ARRAY ARRAY['fitness_programs', 'fitness_gyms', 'fitness_sessions', 'fitness_sets',
                           'fitness_exercise_state', 'fitness_bodyweight', 'fitness_adjustments']
  LOOP
    EXECUTE format('DROP TRIGGER IF EXISTS %I ON public.%I', t || '_touch', t);
    EXECUTE format('CREATE TRIGGER %I BEFORE INSERT OR UPDATE ON public.%I FOR EACH ROW EXECUTE FUNCTION public.fitness_touch()',
                   t || '_touch', t);
    EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', t);

    EXECUTE format('DROP POLICY IF EXISTS %I ON public.%I', t || ' readable by everyone', t);
    EXECUTE format('CREATE POLICY %I ON public.%I FOR SELECT TO anon, authenticated USING (true)',
                   t || ' readable by everyone', t);

    EXECUTE format('DROP POLICY IF EXISTS %I ON public.%I', t || ' insert own', t);
    EXECUTE format('CREATE POLICY %I ON public.%I FOR INSERT TO authenticated WITH CHECK (user_id = (SELECT auth.uid()) AND public.fitness_can_write())',
                   t || ' insert own', t);

    EXECUTE format('DROP POLICY IF EXISTS %I ON public.%I', t || ' update own', t);
    EXECUTE format('CREATE POLICY %I ON public.%I FOR UPDATE TO authenticated USING (user_id = (SELECT auth.uid()) AND public.fitness_can_write()) WITH CHECK (user_id = (SELECT auth.uid()) AND public.fitness_can_write())',
                   t || ' update own', t);

    EXECUTE format('DROP POLICY IF EXISTS %I ON public.%I', t || ' delete own', t);
    EXECUTE format('CREATE POLICY %I ON public.%I FOR DELETE TO authenticated USING (user_id = (SELECT auth.uid()) AND public.fitness_can_write())',
                   t || ' delete own', t);

    EXECUTE format('REVOKE ALL ON public.%I FROM anon, authenticated', t);
    EXECUTE format('GRANT SELECT ON public.%I TO anon', t);
    EXECUTE format('GRANT SELECT, INSERT, UPDATE, DELETE ON public.%I TO authenticated', t);
  END LOOP;
END;
$$;

-- ---------------------------------------------------------------- stale sessions: auto-close 6 h after start

CREATE OR REPLACE FUNCTION public.fitness_close_stale_sessions()
RETURNS integer
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = ''
AS $$
DECLARE
  n integer;
BEGIN
  UPDATE public.fitness_sessions
     SET status = 'auto_closed',
         ended_at = started_at + interval '6 hours'
   WHERE user_id = (SELECT auth.uid())
     AND status = 'active'
     AND started_at < now() - interval '6 hours';
  GET DIAGNOSTICS n = ROW_COUNT;
  RETURN n;
END;
$$;
REVOKE ALL ON FUNCTION public.fitness_close_stale_sessions() FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.fitness_close_stale_sessions() TO authenticated;

